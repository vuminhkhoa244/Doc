package com.example.aidocumentassistant.demo;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Seeds a small demo `employees` table on startup (idempotent) so the SQL
 * agent tool has structured data to query in both dev (H2) and compose (Postgres).
 */
@Component
public class DemoDataSeeder implements ApplicationRunner {
    private static final Logger log = LoggerFactory.getLogger(DemoDataSeeder.class);

    private final JdbcTemplate jdbcTemplate;

    public DemoDataSeeder(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(ApplicationArguments args) {
        try {
            jdbcTemplate.execute("""
                    CREATE TABLE IF NOT EXISTS employees (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name VARCHAR(120) NOT NULL,
                      department VARCHAR(60) NOT NULL,
                      role VARCHAR(80) NOT NULL,
                      salary NUMERIC(12,2) NOT NULL,
                      hired_date DATE NOT NULL,
                      location VARCHAR(60) NOT NULL
                    )
                    """);

            Integer count = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM employees", Integer.class);
            if (count != null && count > 0) {
                return;
            }

            jdbcTemplate.update("""
                    INSERT INTO employees (name, department, role, salary, hired_date, location) VALUES
                    ('Nguyen Van An', 'Engineering', 'Backend Engineer', 45000000, DATE '2022-03-14', 'Ha Noi'),
                    ('Tran Binh', 'Engineering', 'Frontend Engineer', 40000000, DATE '2022-07-01', 'Da Nang'),
                    ('Le Chi', 'Engineering', 'DevOps Engineer', 50000000, DATE '2021-11-22', 'Ha Noi'),
                    ('Pham Duc', 'Engineering', 'ML Engineer', 55000000, DATE '2023-01-09', 'HCMC'),
                    ('Hoang Ha', 'Product', 'Product Manager', 48000000, DATE '2021-05-17', 'Ha Noi'),
                    ('Vu Thi Lan', 'Product', 'Product Designer', 36000000, DATE '2023-08-21', 'Remote'),
                    ('Do Khoa', 'Sales', 'Account Executive', 32000000, DATE '2022-09-05', 'HCMC'),
                    ('Bui Mai', 'Sales', 'Sales Lead', 42000000, DATE '2020-02-10', 'Ha Noi'),
                    ('Nguyen Nam', 'Support', 'Support Engineer', 28000000, DATE '2023-04-03', 'Da Nang'),
                    ('Dang Trang', 'Support', 'Support Specialist', 25000000, DATE '2024-01-15', 'Remote'),
                    ('Phan Thu', 'HR', 'HR Manager', 38000000, DATE '2021-09-13', 'Ha Noi'),
                    ('Doan Vu', 'HR', 'Recruiter', 30000000, DATE '2023-06-26', 'HCMC')
                    """);
            log.info("Seeded demo employees table with 12 rows");
        } catch (Exception exception) {
            log.warn("Demo data seeding skipped: {}", exception.getMessage());
        }
    }
}
